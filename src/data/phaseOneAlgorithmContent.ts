function question(name: string, answer: string, wrongOne: string, wrongTwo: string): PhaseOneQuizQuestion {
  return {
    question: `What is the safest beginner takeaway for ${name}?`,
    options: [answer, wrongOne, wrongTwo],
    correctIndex: 0,
    explanation: `${name} should be understood by purpose and security status first; implementation details only matter after the safe use boundary is clear.`,
  };
}

function makeAlgorithm(
  content: Omit<PhaseOneAlgorithmContent, "lastReviewed" | "quiz" | "glossary" | "references"> & {
    glossary?: string[];
    references?: PhaseOneReference[];
    quizAnswer?: string;
  },
): PhaseOneAlgorithmContent {
  return {
    ...content,
    lastReviewed: reviewed,
    glossary: content.glossary ?? ["plaintext", "ciphertext", "key", "authentication", "integrity"],
    references: content.references ?? [refs.nistTransition],
    quiz: [
      question(
        content.name,
        content.quizAnswer ?? content.recommendation,
        "Use it anywhere because famous algorithms are automatically safe.",
        "Ignore keys, nonces, modes, and protocol context.",
      ),
    ],
  };
}

